"""AapadaOps Operational Resource Optimization & Response Coordination Schemas."""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from app.models.coordination import CoordinationStatus
from app.models.incident import IncidentCategory, IncidentSeverity
from app.models.resource import ResourceStatus, ResourceType
from app.models.team import TeamStatus


# ============================================================================
# Resource & Force Entity View Models
# ============================================================================

class ResourceEntityView(BaseModel):
    """ODRN equipment or inventory asset."""
    id: str
    code: str
    name: str
    category: ResourceType
    organization: str
    district_name: str
    status: ResourceStatus
    quantity: int
    capacity: int
    capacity_unit: str
    latitude: float
    longitude: float
    assigned_incident_id: Optional[str] = None
    assigned_plan_id: Optional[str] = None
    last_updated_time: datetime

    model_config = {"from_attributes": True}


class ResponseTeamEntityView(BaseModel):
    """Tactical disaster response unit."""
    id: str
    code: str
    name: str
    organization: str
    battalion: Optional[str] = None
    team_lead_name: str
    team_lead_phone: str
    total_personnel: int
    specialization: str
    rescue_capacity_persons: int
    current_district_name: str
    status: TeamStatus
    latitude: float
    longitude: float
    assigned_incident_id: Optional[str] = None
    assigned_plan_id: Optional[str] = None
    last_updated_time: datetime

    model_config = {"from_attributes": True}


# ============================================================================
# Optimization Engine Schemas
# ============================================================================

class RecommendationOption(BaseModel):
    """Feasible multi-criteria response recommendation generated by OR-Tools."""
    strategy_id: str  # MINIMAL_TIME, MAXIMAL_CAPACITY, RESERVE_PRESERVATION
    title: str
    recommended_teams: List[ResponseTeamEntityView]
    recommended_resources: List[ResourceEntityView]
    total_personnel_deployed: int
    total_rescue_capacity_persons: int
    estimated_distance_km: float
    estimated_arrival_minutes: float
    telemetry_source: str = "CALCULATED_ESTIMATE"
    is_live_telemetry: bool = False
    reasoning: str
    assumptions: List[str]
    limitations: List[str]
    estimated_resource_impact: Dict[str, Any]
    optimization_score: float = Field(ge=0.0, le=100.0)


class OptimizationRequest(BaseModel):
    """Input payload to trigger OR-Tools resource allocation optimization."""
    incident_id: str
    target_latitude: float
    target_longitude: float
    target_district: str
    target_village: str
    category: IncidentCategory
    severity: IncidentSeverity
    people_stranded: int = Field(default=0, ge=0)
    casualties: int = Field(default=0, ge=0)
    road_access_severed: bool = False
    is_coastal_surge: bool = False
    max_recommendations: int = Field(default=3, ge=1, le=5)


class OptimizationResponse(BaseModel):
    """Set of feasible multi-strategy response recommendations."""
    incident_id: str
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    solver_engine: str = "Google OR-Tools Mixed-Integer Programming (SCIP/CBC)"
    recommendations: List[RecommendationOption]
    safety_notice: str = (
        "AI recommendations are mathematical optimizations for coordinator review. "
        "Autonomous unit dispatch is prohibited. Human coordinator approval is required."
    )


# ============================================================================
# Approval & Coordination Workflow Schemas
# ============================================================================

class PlanApprovalRequest(BaseModel):
    """Coordinator action approving a recommendation plan and assigning assets."""
    chosen_strategy_id: str = Field(..., description="MINIMAL_TIME, MAXIMAL_CAPACITY, or RESERVE_PRESERVATION")
    approval_notes: Optional[str] = None


class PlanAcknowledgmentRequest(BaseModel):
    """Battalion commander or station lead acknowledging dispatch orders."""
    acknowledged_by_lead_name: str = Field(..., min_length=2)
    acknowledgment_notes: Optional[str] = None


class PlanProgressUpdateRequest(BaseModel):
    """Live field progress update reported by deployed force."""
    progress_notes: str = Field(..., min_length=5)
    target_status: str = Field(default="IN_PROGRESS")


class PlanEvidenceAttachmentRequest(BaseModel):
    """Attach photographic or document evidence proving task execution."""
    evidence_file_id: str = Field(..., min_length=1)
    evidence_notes: Optional[str] = None


class PlanHumanClosureRequest(BaseModel):
    """Official administrative closure releasing forces and inventory back to reserve."""
    closure_notes: str = Field(..., min_length=5)


class CoordinationPlanResponse(BaseModel):
    """Full operational coordination plan view model."""
    id: str
    plan_code: str
    incident_id: str
    title: str
    strategy_name: str
    status: CoordinationStatus
    allocated_team_ids: List[str]
    allocated_resource_ids: List[str]
    target_latitude: float
    target_longitude: float
    target_district: str
    target_village: str
    estimated_distance_km: float
    estimated_arrival_minutes: float
    telemetry_source: str
    is_live_telemetry: bool
    reasoning_text: str
    assumptions_text: str
    limitations_text: str
    resource_impact: Dict[str, Any]
    reviewed_by_id: Optional[str] = None
    reviewed_at: Optional[datetime] = None
    approved_by_id: Optional[str] = None
    approved_at: Optional[datetime] = None
    acknowledged_by: Optional[str] = None
    acknowledged_at: Optional[datetime] = None
    progress_notes: Optional[str] = None
    evidence_file_id: Optional[str] = None
    closed_by_id: Optional[str] = None
    closed_at: Optional[datetime] = None
    closure_notes: Optional[str] = None
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}

